CREATE TABLE taggings (
  id BIGINT NOT NULL AUTO_INCREMENT,
  created_at_ms BIGINT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  version INT NOT NULL DEFAULT 1,
  token VARCHAR(32) NOT NULL,
  taggable_id VARCHAR(32) NULL,
  external_entity_id BIGINT NULL,
  target_key VARCHAR(40) NOT NULL,
  tag_id BIGINT NOT NULL,
  operation VARCHAR(8) NOT NULL,
  ldap VARCHAR(96) NULL,
  service VARCHAR(96) NULL,
  note VARCHAR(512) NULL,
  effective_at_ms BIGINT NOT NULL,
  feed_sync_id BIGINT NULL,
  shard INT NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY u_token (token),
  UNIQUE KEY u_fsi (feed_sync_id),
  KEY k_target_tag_eff (target_key, tag_id, effective_at_ms, id),
  KEY k_tag_eff (tag_id, effective_at_ms, id),
  CONSTRAINT c_one_target CHECK ((taggable_id IS NULL) <> (external_entity_id IS NULL)),
  CONSTRAINT c_operation CHECK (operation IN ('ADD', 'REMOVE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
