CREATE TABLE ownerships (
  id BIGINT NOT NULL AUTO_INCREMENT,
  created_at_ms BIGINT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  version INT NOT NULL DEFAULT 1,
  token VARCHAR(32) NOT NULL,
  external_entity_type_id BIGINT NOT NULL,
  external_entity_id BIGINT NULL,
  scope_key VARCHAR(40) NOT NULL,
  aspect VARCHAR(96) NOT NULL,
  owner VARCHAR(96) NOT NULL,
  role VARCHAR(16) NOT NULL,
  operation VARCHAR(8) NOT NULL,
  ldap VARCHAR(96) NULL,
  service VARCHAR(96) NULL,
  note VARCHAR(512) NULL,
  effective_at_ms BIGINT NOT NULL,
  feed_sync_id BIGINT NULL,
  shard INT NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY u_token (token),
  UNIQUE KEY u_fsi (feed_sync_id),
  KEY k_scope_aspect_eff (scope_key, aspect, effective_at_ms, id),
  KEY k_type_eff (external_entity_type_id, effective_at_ms, id),
  KEY k_owner_eff (owner, effective_at_ms, id),
  CONSTRAINT c_own_role CHECK (role IN ('OWNER', 'STAKEHOLDER')),
  CONSTRAINT c_own_operation CHECK (operation IN ('CLAIM', 'RELEASE', 'AFFIRM'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
