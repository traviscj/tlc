CREATE TABLE approvables (
  id BIGINT NOT NULL AUTO_INCREMENT,
  created_at_ms BIGINT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  version INT NOT NULL DEFAULT 1,
  token VARCHAR(32) NOT NULL,
  external_entity_id BIGINT NOT NULL,
  approval_context TEXT NULL,
  approval_rule_token VARCHAR(32) NOT NULL,
  approval_state VARCHAR(16) NOT NULL,
  requested_by VARCHAR(96) NOT NULL,
  requested_via_service VARCHAR(96) NULL,
  client_id VARCHAR(96) NULL,
  approved_at_ms BIGINT NULL,
  executed_at_ms BIGINT NULL,
  executed_by VARCHAR(96) NULL,
  declined_at_ms BIGINT NULL,
  declined_by VARCHAR(96) NULL,
  decline_reason TEXT NULL,
  feed_sync_id BIGINT NULL,
  shard INT NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY u_token (token),
  UNIQUE KEY u_client_id (client_id),
  UNIQUE KEY u_fsi (feed_sync_id),
  KEY k_entity (external_entity_id, id),
  KEY k_state (approval_state, id),
  CONSTRAINT c_state CHECK (approval_state IN ('PENDING', 'APPROVED', 'EXECUTED', 'DECLINED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
