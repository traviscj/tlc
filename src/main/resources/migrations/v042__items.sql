CREATE TABLE items (
  id BIGINT NOT NULL AUTO_INCREMENT,
  created_at_ms BIGINT NOT NULL,
  updated_at_ms BIGINT NOT NULL,
  token VARCHAR(32) NOT NULL,
  source VARCHAR(64) NOT NULL,
  source_key VARCHAR(255) NOT NULL,
  kind VARCHAR(32) NOT NULL,
  title VARCHAR(500) NOT NULL,
  detail TEXT NULL,
  url VARCHAR(1000) NULL,
  state VARCHAR(16) NOT NULL,
  snoozed_until_ms BIGINT NULL,
  due_at_ms BIGINT NULL,
  priority DOUBLE NULL,
  derived TINYINT(1) NOT NULL DEFAULT 0,
  cleared TINYINT(1) NOT NULL DEFAULT 0,
  last_seen_ms BIGINT NULL,
  closed_at_ms BIGINT NULL,
  closed_by VARCHAR(96) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY u_token (token),
  UNIQUE KEY u_source_key (source, source_key),
  KEY k_state (state, snoozed_until_ms)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
